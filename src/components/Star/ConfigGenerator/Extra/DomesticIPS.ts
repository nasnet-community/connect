export const generateDomesticIPScript = (
    time: string,
    interval: FrequencyValue = "Bi-Weekly",
): RouterConfig => {
    // Generate a unique UUID for this script instance
    const generatedUserId = generateUUID();

    const scriptCommands = DomesticIPsScript.map((line) =>
        line.replace("{{USER_ID}}", generatedUserId),
    );

    // Create the RouterConfig with the script content
    const scriptContent: RouterConfig = {
        "": scriptCommands,
    };

    // Convert FrequencyValue to interval format
    const getIntervalValue = (frequency: FrequencyValue): string => {
        switch (frequency) {
            case "Daily":
                return "1d";
            case "Bi-Weekly":
                return "14d";
            case "Weekly":
                return "7d";
            case "Monthly":
                return "30d";
            default:
                return "14d";
        }
    };

    // Convert time from "HH:MM" to appropriate format and create scheduled script
    const [hour, minute] = time.split(":");
    const startTime = `${hour}:${minute}:00`;

    const scheduledUpdaterConfig = ScriptAndScheduler({
        ScriptContent: scriptContent,
        Name: "DomesticIPUpdate",
        interval: getIntervalValue(interval),
        startTime: startTime,
    });

    const bootRecoveryConfig: RouterConfig = {
        "/system scheduler": [
            `add interval=00:00:00 name=DomesticIPUpdate-BootCheck on-event=":delay 5m; :local currentCount [:len [/ip firewall address-list find list=DOMAddList]]; :if ($currentCount < 100) do={ :log warning \\"SecureListUpdate: Boot guard detected only $currentCount entries, running DomesticIPUpdate\\"; /system script run DomesticIPUpdate } else={ :log info \\"SecureListUpdate: Boot guard healthy ($currentCount entries)\\" }" policy=ftp,reboot,read,write,policy,test,password,sniff,sensitive,romon start-time=startup`,
        ],
    };

    return mergeMultipleConfigs(scheduledUpdaterConfig, bootRecoveryConfig);
};

